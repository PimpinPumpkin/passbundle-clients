#!/usr/bin/env node
// Keykeeper: refreshes what we know about sites from apple/password-manager-
// resources (MIT): their password rules, which generated passwords follow,
// and their change-password pages. Pass the commit to take them from; the
// files it writes record it, so a change is a reviewable diff.
//
//   node scripts/keykeeper/update-site-data.mjs <commit-sha>
//
// See DESIGN.md, "Health (better than Watchtower)".

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const commit = process.argv[2];
if (!/^[0-9a-f]{40}$/.test(commit ?? "")) {
  console.error("usage: update-site-data.mjs <40-character commit sha>");
  process.exit(1);
}

const folder = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../libs/common/src/tools/keykeeper",
);
const isDomain = (domain) => /^[a-z0-9.-]+$/.test(domain);

async function fetchQuirk(file) {
  const source = `https://raw.githubusercontent.com/apple/password-manager-resources/${commit}/quirks/${file}`;
  const response = await fetch(source);
  if (!response.ok) {
    console.error(`couldn't fetch ${source}: ${response.status}`);
    process.exit(1);
  }
  return response.json();
}

/** Writes a domain-to-text table as a TypeScript module, in the repo's own format. */
function writeTable(outFile, sourceFile, doc, exportName, entries) {
  const out = path.join(folder, outFile);
  const lines = entries.map(
    ([domain, text]) => `  ${JSON.stringify(domain)}: ${JSON.stringify(text)},`,
  );
  fs.writeFileSync(
    out,
    `// Generated by scripts/keykeeper/update-site-data.mjs. Don't edit by hand.
// Source: apple/password-manager-resources, quirks/${sourceFile} at
// ${commit}.
// Copyright Apple Inc., MIT License (see APPLE-LICENSE.md in this folder).

/** ${doc} */
export const ${exportName}: Readonly<Record<string, string>> = {
${lines.join("\n")}
};
`,
  );
  execFileSync("npx", ["prettier", "--write", out], { stdio: "inherit" });
  console.log(`wrote ${entries.length} sites to ${path.relative(process.cwd(), out)}`);
}

/** Keeps the entries whose domain and value pass `valid`, sorted by domain. */
function entriesOf(data, valueOf, valid) {
  const kept = [];
  for (const domain of Object.keys(data).sort()) {
    const value = valueOf(data[domain]);
    if (!isDomain(domain) || typeof value !== "string" || !valid(value)) {
      console.error(`skipped ${domain}`);
      continue;
    }
    kept.push([domain, value]);
  }
  return kept;
}

writeTable(
  "site-password-rules.data.ts",
  "password-rules.json",
  "Sites' password rules, by domain, in Apple's password rules language.",
  "SITE_PASSWORD_RULES",
  entriesOf(
    await fetchQuirk("password-rules.json"),
    (entry) => entry?.["password-rules"],
    () => true,
  ),
);

writeTable(
  "site-change-password-urls.data.ts",
  "change-password-URLs.json",
  "Sites' change-password pages, by domain.",
  "SITE_CHANGE_PASSWORD_URLS",
  entriesOf(
    await fetchQuirk("change-password-URLs.json"),
    (url) => url,
    (url) => /^https:\/\/[^\s"]+$/.test(url),
  ),
);
