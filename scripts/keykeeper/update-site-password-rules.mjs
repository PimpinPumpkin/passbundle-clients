#!/usr/bin/env node
// Keykeeper: refreshes the sites' password rules that generated passwords
// follow, from apple/password-manager-resources (MIT). Pass the commit to take
// them from; the file it writes records it, so a change is a reviewable diff.
//
//   node scripts/keykeeper/update-site-password-rules.mjs <commit-sha>
//
// See DESIGN.md, "Health (better than Watchtower)".

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const commit = process.argv[2];
if (!/^[0-9a-f]{40}$/.test(commit ?? "")) {
  console.error("usage: update-site-password-rules.mjs <40-character commit sha>");
  process.exit(1);
}

const source = `https://raw.githubusercontent.com/apple/password-manager-resources/${commit}/quirks/password-rules.json`;
const response = await fetch(source);
if (!response.ok) {
  console.error(`couldn't fetch ${source}: ${response.status}`);
  process.exit(1);
}
const data = await response.json();

const rules = {};
for (const domain of Object.keys(data).sort()) {
  const text = data[domain]?.["password-rules"];
  if (typeof text !== "string" || !/^[a-z0-9.-]+$/.test(domain)) {
    console.error(`skipped ${domain}: not a domain with password rules`);
    continue;
  }
  rules[domain] = text;
}

const out = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../libs/common/src/tools/keykeeper/site-password-rules.data.ts",
);
const lines = Object.entries(rules).map(
  ([domain, text]) => `  ${JSON.stringify(domain)}: ${JSON.stringify(text)},`,
);
fs.writeFileSync(
  out,
  `// Generated by scripts/keykeeper/update-site-password-rules.mjs. Don't edit by hand.
// Source: apple/password-manager-resources, quirks/password-rules.json at
// ${commit}.
// Copyright Apple Inc., MIT License (see APPLE-LICENSE.md in this folder).

/** Sites' password rules, by domain, in Apple's password rules language. */
export const SITE_PASSWORD_RULES: Readonly<Record<string, string>> = {
${lines.join("\n")}
};
`,
);
// In the repo's own format, so prettier --check passes.
execFileSync("npx", ["prettier", "--write", out], { stdio: "inherit" });
console.log(
  `wrote ${Object.keys(rules).length} sites' rules to ${path.relative(process.cwd(), out)}`,
);
